/* Camera v11 visual-only enhancer. No camera API, state, tests or report writes. */
(()=>{
"use strict";
const lensTitle=document.getElementById("lensGuideTitle");
const guide=document.getElementById("cameraLensGuide");
const diagram=document.getElementById("lensGuideDevice");
const test=document.getElementById("test");
if(!lensTitle||!guide||!diagram||!test)return;
let previous="";
function redraw(){
 const label=(lensTitle.textContent||"").trim();
 if(!label||label===previous)return;
 previous=label;
 const kind=/flash|torch/i.test(label)?"flash":
   /ultra-wide/i.test(label)?"ultra":
   /telephoto/i.test(label)?"tele":
   /LiDAR/i.test(label)?"lidar":
   /face ID|TrueDepth/i.test(label)?"faceid":
   /selfie|front/i.test(label)?"front":
   /focus/i.test(label)?"focus":
   /stabili/i.test(label)?"stability":"rear";
 test.dataset.irLens=kind;
 guide.dataset.irLens=kind;
 // Recreate only CSS animation on the model illustration. SVG, generated by
 // the tested model renderer, is never modified or restyled by geometry here.
 if(diagram.getAttribute("hidden")===null){
   diagram.style.animation="none";
   void diagram.getBoundingClientRect().width;
   diagram.style.animation="";
 }
}
new MutationObserver(()=>requestAnimationFrame(redraw))
 .observe(lensTitle,{characterData:true,childList:true,subtree:true});
redraw();
})();
