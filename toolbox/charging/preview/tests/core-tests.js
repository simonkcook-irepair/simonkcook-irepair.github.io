/* iRepair Charging Diagnostics: pure plan/regression tests. Run from repo root:
 node toolbox/charging/preview/tests/core-tests.js */
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm"),assert=require("node:assert/strict");
const dir=path.resolve(__dirname,".."),scope={};
for(const file of ["models.js","core.js"])vm.runInNewContext(fs.readFileSync(path.join(dir,file),"utf8"),{window:scope,Date});
const api=scope.IRepairChargingCore,cat=scope.IRepairDeviceCatalogue;
let n=0;function yes(name,predicate){assert.ok(predicate,name);n++;console.log("PASS",name)}
const plan=api.makePlan("iphone-15-pro",cat);
yes("Exactly six checks",plan.steps.length===6);
yes("Safe setup precedes any powered test",plan.steps[0].id==="safety");
yes("Charging test stages properly sequenced",plan.steps.map(x=>x.id).join(",")==="safety,wired,swap,port,wireless,behaviour");
yes("iPhone 15 Pro uses USB-C",plan.connector==="USB-C");
yes("iPhone 14 Pro uses Lightning",api.makePlan("iphone-14-pro",cat).connector==="Lightning");
yes("iPhone SE 2022 uses Lightning",api.makePlan("iphone-se-2022",cat).connector==="Lightning");
yes("Unknown iPhone model never auto-identified",api.makePlan("",cat).modelName==="Not selected");
yes("Unknown model avoids definitive connector",api.makePlan("",cat).connector.includes("not selected"));
yes("All steps describe a user observation",plan.steps.every(s=>s.guide&&s.expect&&s.question&&s.note));
yes("Every stage supports optional fault reporting",plan.steps.every(s=>api.symptomChoices[s.id]?.length>=3));
yes("Manual observations are not fabricated sensor readings",!api.report(plan,{},{}).includes("real sensor samples"));
yes("Report explicitly forbids false hardware verification",api.report(plan,{},{}).includes("No Safari charging state"));
yes("No diagnostic step attempts invasive cleaning",!plan.steps.some(s=>/insert a metal|scrape.*port|clean.*sharp/i.test(s.guide)));
let answers={};for(const s of plan.steps)answers=api.addAnswer(answers,s.id,s.id==="port"?"FAIL":s.id==="wireless"?"UNABLE":"PASS");
const totals=api.tally(plan,answers);
yes("Tally handles mixed PASS FAIL UNABLE",totals.PASS===4&&totals.FAIL===1&&totals.UNABLE===1);
yes("Unanswered stay unanswered",api.tally(plan,{}).UNANSWERED===6);
assert.throws(()=>api.addAnswer({},"missing","PASS"));n++;
assert.throws(()=>api.addAnswer({},"port","SUCCESS"));n++;
yes("Safety fault advice instructs stopping charging",api.interpretations({safety:"FAIL"}).some(h=>/do not continue charging/i.test(h.title)));
yes("Wireless pass and wired fail suggests cautious wired path clue",api.interpretations({wired:"FAIL",wireless:"PASS"}).some(h=>h.title.includes("Wired charging path")&&h.detail.includes("not a confirmed")));
yes("Known-good cable success suggests original accessory",api.interpretations({wired:"FAIL",swap:"PASS"}).some(h=>h.detail.includes("first cable")));
yes("Wireless fail with wired success prompts setup",api.interpretations({wireless:"FAIL",wired:"PASS"}).some(h=>h.title.includes("Wireless")));
const report=api.report(plan,answers,{port:["Connector feels loose","Fake unrecognised test"]});
yes("Report includes selected iPhone and connector",report.includes("iPhone 15 Pro")&&report.includes("USB-C"));
yes("Report includes symptom selected from allow-list",report.includes("Connector feels loose"));
yes("Report does not include user-injected symptom",!report.includes("Fake unrecognised"));
yes("Report keeps customer observation provenance",report.includes("manually selected by the customer"));
yes("Safety guidance included in report",report.includes("Do not charge a wet"));
yes("Battery voltage and power not invented",!report.includes("14.6 W")&&!report.includes("4.2 V"));
const html=fs.readFileSync(path.join(dir,"index.html"),"utf8");
const app=fs.readFileSync(path.join(dir,"app.js"),"utf8");
const css=fs.readFileSync(path.join(dir,"visual.css"),"utf8");
yes("Premium phone hero has battery and power bolt",html.includes('class="chargingHeroSvg"')&&html.includes('class="chargingBolt"'));
yes("Hero uses shine only within screen",html.includes('<div class="screenGlow"></div><div class="screenGlow2"></div>'));
yes("Hero override keeps phone centered with transform",css.includes('#home .phoneStage.chargingHero .phoneArt')&&css.includes("translate(-50%,-50%) scale(.58)!important"));
yes("Customer receives do-this and expected-result panels",html.includes("DO THIS")&&html.includes("WHAT TO LOOK FOR"));
yes("No fake live sensor readout presented in HTML",!html.includes("YOUR IPHONE · LIVE"));
yes("Fails safety test stop procedure",app.includes('index===0&&answers.safety!=="PASS"'));
yes("Safety Unable also terminates procedure",app.includes('index===0&&answers.safety!=="PASS"'));
yes("All three result buttons available",["PASS","FAIL","UNABLE"].every(x=>html.includes('data-answer="'+x+'"')));
yes("Expandable method and report copying available",html.includes('<details class="technicalPanel"')&&html.includes('id="copyReport"'));
yes("No hardware sensor permission requested",!app.includes("requestPermission(")&&!app.includes("getBattery("));
console.log("ALL",n,"CHARGING CHECKS PASSED");
